-- R08-03 (Review 08-2): нормализация значения параметра для поиска конфликта требований (И-08-16). В 0020 значение
-- сравнивалось как текст без пробелов (`100` ≠ `100.0` — ложный конфликт, `5 x 10` = `5x10`). Теперь число и текст
-- канонизируются раздельно; единица остаётся частью ключа значения после `unit_normalize`. Применённая миграция 0020
-- не меняется (ADR-002: мигратор отклоняет изменённый файл); функции, объявленные в 0020, заменяются здесь.
-- Охранник ревизии требования и проекции вызывают их через `requirement_parameter_conflicts` — других изменений нет.

-- Пробельные символы записи: обычные пробелы, табуляция, переводы строк, неразрывный (U+00A0), цифровой (U+2007),
-- тонкий (U+2009) и узкий неразрывный (U+202F) пробелы — сводятся к одному пробелу.
CREATE FUNCTION requirement_param_spaces(p text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT btrim(regexp_replace(p, '[\s    ]+', ' ', 'g'))
$$;

-- Число: после сведения пробелов запись целиком — необязательный знак, целая часть (цифры подряд или группы по три
-- цифры через пробел: `1 000`), необязательная дробная часть после одной точки или запятой. Иначе — не число (NULL):
-- `B30`, `IP54`, `5x10`, `1e3`, `1.2.3`, `10 00`, `.5` остаются текстом. Каноническое представление — значение
-- `numeric` без незначащих нулей дробной части (`trim_scale`): `100`, `100.0`, `100,00`, `+100` → `100`; `-0` → `0`.
CREATE FUNCTION requirement_param_number(p text) RETURNS numeric
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN v ~ '^[+-]?([0-9]+|[0-9]{1,3}( [0-9]{3})+)([.,][0-9]+)?$'
              THEN trim_scale(replace(replace(v, ' ', ''), ',', '.')::numeric) END
    FROM (SELECT requirement_param_spaces(p) AS v) x
$$;

-- Ключ значения: `n:<число>` или `t:<текст>` и `|<единица>`. Текст — trim, нижний регистр, пробелы внутри сведены к
-- одному и не удаляются (`5 x 10` ≠ `5x10`); запятая и точка в тексте не заменяются.
CREATE OR REPLACE FUNCTION requirement_param_value(p jsonb) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT coalesce('n:' || requirement_param_number(p ->> 'value')::text, 't:' || lower(requirement_param_spaces(p ->> 'value')))
         || '|' || coalesce(unit_normalize(p ->> 'unit'), '')
$$;
